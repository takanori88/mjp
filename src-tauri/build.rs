fn main() {
    #[cfg(feature = "perf")]
    const COMMANDS: &[&str] = &[
        "get_document",
        "close_preview",
        "open_external",
        "perf_mark",
    ];
    #[cfg(not(feature = "perf"))]
    const COMMANDS: &[&str] = &["get_document", "close_preview", "open_external"];

    // Generated permissions survive feature changes in the same checkout.
    #[cfg(not(feature = "perf"))]
    match std::fs::remove_file("permissions/autogenerated/perf_mark.toml") {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => panic!("cannot remove generated perf permission: {error}"),
    }

    let attributes = tauri_build::Attributes::new()
        .app_manifest(tauri_build::AppManifest::new().commands(COMMANDS));
    #[cfg(feature = "perf")]
    let attributes = attributes.capabilities_path_pattern("capabilities/**/*.json");
    #[cfg(not(feature = "perf"))]
    let attributes = attributes.capabilities_path_pattern("capabilities/*.json");
    println!("cargo:rerun-if-changed=capabilities");
    tauri_build::try_build(attributes).expect("cannot build application permissions");
}
